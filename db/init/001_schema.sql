DROP TABLE IF EXISTS bookings, area_tariffs, tariffs, areas CASCADE;

CREATE TABLE areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    radius DOUBLE PRECISION NOT NULL CHECK (radius > 0)
);

CREATE TABLE tariffs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE area_tariffs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id BIGINT NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
    tariff_id BIGINT NOT NULL REFERENCES tariffs(id) ON DELETE CASCADE,
    price_per_km NUMERIC(12, 2) NOT NULL CHECK (price_per_km >= 0),
    CONSTRAINT uq_area_tariff UNIQUE (area_id, tariff_id)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tariff_id BIGINT NOT NULL REFERENCES tariffs(id),
    start_datetime TIMESTAMPTZ NOT NULL,
    start_latitude DOUBLE PRECISION NOT NULL CHECK (start_latitude BETWEEN -90 AND 90),
    start_longitude DOUBLE PRECISION NOT NULL CHECK (start_longitude BETWEEN -180 AND 180),
    end_latitude DOUBLE PRECISION NOT NULL CHECK (end_latitude BETWEEN -90 AND 90),
    end_longitude DOUBLE PRECISION NOT NULL CHECK (end_longitude BETWEEN -180 AND 180),
    calculated_price NUMERIC(12, 2) NOT NULL CHECK (calculated_price >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'RUB',
    booking_status VARCHAR(20) NOT NULL CHECK (booking_status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX ix_area_tariffs_tariff_id ON area_tariffs(tariff_id);
